import esbuild from "esbuild";
import process from "process";
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const version = JSON.parse(fs.readFileSync("manifest.json", "utf8")).version;
const sourceFiles = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
	const file = path.join(dir, entry.name);
	return entry.isDirectory() ? sourceFiles(file) : [file];
});
const buildHash = createHash("sha256");
for (const file of [...sourceFiles("src"), "manifest.json", "package.json", "pnpm-lock.yaml", "esbuild.config.mjs"].sort()) {
	buildHash.update(file.replaceAll(path.sep, "/"));
	buildHash.update(fs.readFileSync(file));
}
const buildId = buildHash.digest("hex").slice(0, 12);

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	define: {
		__FNS_BUILD_VERSION__: JSON.stringify(version),
		__FNS_BUILD_ID__: JSON.stringify(buildId),
	},
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		"fs",
		"path",
		"crypto",
		"os",
		"http",
		"https",
		"url",
		"events",
		"stream",
		"util",
		"child_process",
		"zlib"
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
